// Edge function: bas-worksheet-pdf  (SC-3.D.01)
//
// Renders a BAS worksheet PDF for an org + AU FY quarter. Calls the
// generate_bas_worksheet RPC (SC-3.C.03) and lays its labels out via the shared
// PDF helper (_shared/pdf/worksheet.ts) — the first consumer of that helper,
// which Phase 5 statements reuse.
//
// AUTH: user-invokable. The RPC is SECURITY INVOKER, so the caller's JWT is
// forwarded into a caller-scoped client and RLS scopes the worksheet to the
// caller's orgs (per [[edge-fn-caller-org-authz]] — never a service-role load by
// id). An org the caller can't access simply yields a zero worksheet, not a leak.
//
// Request body: { organization_id: uuid, fy_start_year: int, quarter: 1..4 }
// Response: application/pdf bytes (200) or a JSON error.
//
// DEPLOY: requires generate_bas_worksheet (0120-0122) applied; deploy with
// verify_jwt=true (the gateway validates the JWT before the caller-scoped client
// re-applies RLS). Smoke-tested via tests/bas-worksheet-pdf.test.ts (skip-safe).

import { createClient } from "https://esm.sh/@supabase/supabase-js@2";
import { corsHeaders, preflight } from "../_shared/cors.ts";
import { requireEnv } from "../_shared/env.ts";
import { renderWorksheetPdf, type WorksheetDoc } from "../_shared/pdf/worksheet.ts";

interface RequestBody {
  organization_id?: string;
  fy_start_year?: number;
  quarter?: number;
}

interface BasPayload {
  fy_start_year?: number;
  quarter?: number;
  due_date?: string | null;
  quarter_start?: string | null;
  quarter_end?: string | null;
  gst?: Record<string, number>;
  payg_withholding?: Record<string, number>;
  payg_instalment?: Record<string, number> | null;
  summary?: Record<string, number>;
}

function json(body: unknown, status = 200): Response {
  return new Response(JSON.stringify(body), {
    status,
    headers: { ...corsHeaders, "Content-Type": "application/json" },
  });
}

/** Cents (any) -> "$1,234.00". */
function money(cents: unknown): string {
  const n = Number(cents ?? 0);
  return `$${(n / 100).toLocaleString("en-AU", { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;
}

/** Map the generate_bas_worksheet payload into the generic worksheet doc. */
function toWorksheetDoc(p: BasPayload, fy: number, quarter: number): WorksheetDoc {
  const gst = p.gst ?? {};
  const payg = p.payg_withholding ?? {};
  const summary = p.summary ?? {};
  const period =
    p.quarter_start && p.quarter_end
      ? `${p.quarter_start} to ${p.quarter_end}`
      : "period n/a (no activity)";
  const due = p.due_date ? `, due ${p.due_date}` : "";

  const sections: WorksheetDoc["sections"] = [
    {
      heading: "GST",
      caption: "From invoices (sales) and bills (purchases) - v_bas_quarterly",
      rows: [
        { label: "G1   Total sales (inc GST)", value: money(gst["G1"]) },
        { label: "G10  Capital purchases", value: money(gst["G10"]) },
        { label: "G11  Non-capital purchases (inc GST)", value: money(gst["G11"]) },
        { label: "1A   GST on sales", value: money(gst["1A"]) },
        { label: "1B   GST on purchases", value: money(gst["1B"]) },
      ],
    },
    {
      heading: "PAYG withholding",
      caption: "From finalised pay runs (pay slips)",
      rows: [
        { label: "W1   Total salary, wages and payments", value: money(payg["W1"]) },
        { label: "W2   Amounts withheld from W1", value: money(payg["W2"]) },
        { label: "W4   Amounts withheld (no ABN)", value: money(payg["W4"]) },
        { label: "W5   Total amounts withheld", value: money(payg["W5"]) },
        { label: "4    PAYG tax withheld", value: money(payg["4"]) },
      ],
    },
  ];

  if (p.payg_instalment) {
    const inst = p.payg_instalment;
    sections.push({
      heading: "PAYG instalment",
      caption: "PAYG-I registered - instalment amount is ATO-notified (not yet sourced)",
      rows: [
        { label: "T7   PAYG instalment amount", value: money(inst["T7"]) },
        { label: "5A   PAYG income tax instalment", value: money(inst["5A"]) },
        { label: "5B   Credit from PAYG instalment variation", value: money(inst["5B"]) },
      ],
    });
  }

  sections.push({
    heading: "Summary",
    caption: "Net amount = (1A + 4 + 5A) - (1B + 5B). Positive = payable to the ATO.",
    rows: [{ label: "9    Net amount", value: money(summary["9_net_amount_cents"]) }],
  });

  return {
    title: "Business Activity Statement - Worksheet",
    subtitle: `FY ${fy}-${fy + 1}, Quarter ${quarter} (${period}${due}) - DRAFT, not lodged`,
    sections,
    footer:
      "Draft worksheet generated by Looplet Accounting. Verify against source records before lodging.",
  };
}

Deno.serve(async (req: Request) => {
  const pre = preflight(req);
  if (pre) return pre;
  try {
    const authHeader = req.headers.get("Authorization");
    if (!authHeader) return json({ ok: false, error: "Unauthorized" }, 401);

    const supabaseUrl = requireEnv("SUPABASE_URL");
    const anonKey = requireEnv("SUPABASE_ANON_KEY");

    const body = (await req.json().catch(() => ({}))) as RequestBody;
    const org = (body.organization_id ?? "").trim();
    const fy = body.fy_start_year;
    const quarter = body.quarter;
    if (!org) return json({ ok: false, error: "organization_id is required" }, 400);
    if (typeof fy !== "number" || !Number.isInteger(fy)) {
      return json({ ok: false, error: "fy_start_year (integer) is required" }, 400);
    }
    if (typeof quarter !== "number" || quarter < 1 || quarter > 4) {
      return json({ ok: false, error: "quarter must be 1..4" }, 400);
    }

    // Caller-scoped client: the user's JWT rides every request, so the SECURITY
    // INVOKER RPC's RLS scopes the worksheet to the caller's orgs.
    const client = createClient(supabaseUrl, anonKey, {
      global: { headers: { Authorization: authHeader } },
      auth: { persistSession: false },
    });

    const { data, error } = await client.rpc("generate_bas_worksheet", {
      p_org: org,
      p_fy_start_year: fy,
      p_quarter: quarter,
    });
    if (error) return json({ ok: false, error: error.message }, 500);
    if (!data) return json({ ok: false, error: "no worksheet payload" }, 404);

    const pdf = await renderWorksheetPdf(toWorksheetDoc(data as BasPayload, fy, quarter));

    // Copy into an ArrayBuffer-backed view so the body type is unambiguous:
    // pdf-lib returns Uint8Array<ArrayBufferLike>, but Response/BodyInit wants
    // Uint8Array<ArrayBuffer> under the current TS lib (the copy is cheap here).
    const pdfBytes = new Uint8Array(pdf);
    return new Response(pdfBytes, {
      status: 200,
      headers: {
        ...corsHeaders,
        "Content-Type": "application/pdf",
        "Content-Disposition": `attachment; filename="bas-worksheet-FY${fy}-Q${quarter}.pdf"`,
      },
    });
  } catch (err) {
    const msg = err instanceof Error ? err.message : String(err);
    return json({ ok: false, error: msg }, 500);
  }
});
